@router.post(
    "/projects/{project_id}/cleanse/preview",
    response_model=CleansePreviewResponse,
    summary="Dry run — generate SQL and count affected rows without changing data",
)
def preview_cleanse(
    project_id: str,
    body: CleansePreviewRequest,
    db: Session = Depends(get_db),
):
    """
    Converts a plain English instruction to SQL via Ollama/GPT-4o,
    counts how many rows would be affected, returns a before-sample.
    NO data is modified.
    """
    return preview_cleansing(project_id, body.instruction, body.table_name)


@router.post(
    "/projects/{project_id}/cleanse/execute",
    response_model=CleanseExecuteResponse,
    summary="Execute a confirmed cleansing SQL statement",
)
def execute_cleanse(
    project_id: str,
    body: CleanseExecuteRequest,
    db: Session = Depends(get_db),
):
    """
    Executes the SQL from a confirmed preview.
    Saves the step to the cleansing playbook in PostgreSQL.
    """
    result = execute_cleansing(project_id, body.sql, body.table_name)
    if result.get("status") == "executed":
        save_playbook_step(
            db, project_id, body.instruction, body.sql, body.affected_rows
        )
        log_audit(db, project_id, "cleanse_executed", {
            "instruction": body.instruction,
            "rows":        body.affected_rows,
        })
    return {**result, "rows_affected": body.affected_rows}


@router.get(
    "/projects/{project_id}/cleanse/playbook",
    response_model=PlaybookResponse,
    summary="Get all cleansing steps saved for this project",
)
def get_project_playbook(project_id: str, db: Session = Depends(get_db)):
    """Returns the ordered list of cleansing steps (the playbook)."""
    return {"steps": get_playbook(db, project_id)}


@router.post(
    "/projects/{project_id}/cleanse/replay",
    response_model=ReplayResponse,
    summary="Replay all playbook steps on current data",
)
def replay_all_steps(project_id: str, db: Session = Depends(get_db)):
    """
    Re-applies all saved cleansing steps in order.
    Useful after re-uploading source data.
    """
    steps   = get_playbook(db, project_id)
    results = replay_playbook(project_id, steps)
    log_audit(db, project_id, "playbook_replayed", {
        "steps_executed": results["steps_executed"],
    })
    return results


@router.get(
    "/projects/{project_id}/cleanse/download",
    summary="Download cleansed data as CSV",
)
def download_cleansed_data(project_id: str):
    """Download the cleansed raw_data table as CSV"""
    from fastapi.responses import StreamingResponse
    from app.services.duckdb_service import get_conn
    import io
    
    conn = get_conn(project_id, read_only=True)
    df = conn.execute("SELECT * FROM raw_data").fetchdf()
    conn.close()
    
    # Convert to CSV
    csv_buffer = io.StringIO()
    df.to_csv(csv_buffer, index=False)
    csv_buffer.seek(0)
    
    return StreamingResponse(
        io.BytesIO(csv_buffer.getvalue().encode()),
        media_type="text/csv",
        headers={"Content-Disposition": f"attachment; filename=cleansed_data_{project_id[:8]}.csv"}
    )


# ── Column-level transformation status (Point 7) ─────────────────────────────

@router.get(
    "/projects/{project_id}/cleanse/column-status",
    summary="Point 7 — Per-column transformation status after validation",
)
def get_column_transformation_status(project_id: str, db: Session = Depends(get_db)):
    """
    Returns per-column transformation status for all approved mappings.

    For each column:
      - transformation_status:  Success | Partially Cleaned | Needs Review | Failed
      - dedup_status:           Unique | Duplicate Found
      - error_count / error_pct: how many rows failed on this column
      - target_field:           D365 API field name (Point 8)
      - selected_for_migration: True/False (Point 10)

    Requires: validation must have been run first.
    """
    from app.services.postgres_services import get_approved_mappings
    from app.services.validator_fast import _compute_column_status
    from app.services.duckdb_service import execute_query
    from sqlalchemy import text
    import pandas as pd

    mappings = get_approved_mappings(db, project_id)
    if not mappings:
        return {"error": "No approved mappings found. Complete mapping step first."}

    # Load errors already saved from last validation run
    saved_errors = db.execute(text("""
        SELECT rule_type, source_column, error_message, row_number, original_value
        FROM errors.validation_failures
        WHERE project_id = :pid
    """), {"pid": project_id}).fetchall()

    errors = [dict(r._mapping) for r in saved_errors]

    # Load the data to compute total row count
    try:
        df = execute_query(project_id, "SELECT COUNT(*) as cnt FROM raw_data")
        total_rows = int(df["cnt"].iloc[0]) if len(df) > 0 else 0
    except Exception as e:
        return {"error": f"Could not read data: {str(e)}"}

    column_status = _compute_column_status(total_rows, mappings, errors)

    # Summary counts
    status_counts = {}
    for col in column_status:
        s = col["transformation_status"]
        status_counts[s] = status_counts.get(s, 0) + 1

    return {
        "project_id":    project_id,
        "total_columns": len(column_status),
        "summary":       status_counts,
        "columns":       column_status,
    }
